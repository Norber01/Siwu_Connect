// Bundles firebase/firestore.rules and firestore.indexes.json into the API Worker so the
// in-app "Set up Siwu Connect" button can install them (no computer needed).
// Run after changing either file: `npm run gen:assets` (CI checks they are in sync).
import { readFileSync, writeFileSync } from 'node:fs';

const rules = readFileSync('firebase/firestore.rules', 'utf8');
const indexes = JSON.parse(readFileSync('firebase/firestore.indexes.json', 'utf8')).indexes;
writeFileSync(
  'apps/api/src/generated/firebase-assets.ts',
  `// GENERATED by scripts/gen-firebase-assets.mjs — do not edit by hand.\n` +
    `export const FIRESTORE_RULES = ${JSON.stringify(rules)};\n\n` +
    `export const FIRESTORE_INDEXES: Array<{ collectionGroup: string; queryScope: string; fields: Array<Record<string, string>> }> = ${JSON.stringify(indexes, null, 2)};\n`,
);
console.log(`Wrote rules (${rules.length} chars) and ${indexes.length} indexes.`);
