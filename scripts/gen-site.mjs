// Embeds the built web app (apps/web/dist, without source maps) into the site Worker.
// Run after `npm run build`: `node scripts/gen-site.mjs`.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const dir = 'apps/web/dist';
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.webmanifest': 'application/manifest+json',
  '.json': 'application/json', '.txt': 'text/plain; charset=utf-8', '.woff2': 'font/woff2', '.xml': 'application/xml; charset=utf-8',
};
const files = walk(dir).filter((f) => !f.endsWith('.map'));
const entries = files.map((f) => {
  const path = '/' + relative(dir, f).split('\\').join('/');
  const b64 = readFileSync(f).toString('base64');
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(types[extname(f)] ?? 'application/octet-stream')}, b64: ${JSON.stringify(b64)} },`;
});
writeFileSync(
  'apps/site/src/files.gen.ts',
  `// GENERATED by scripts/gen-site.mjs from apps/web/dist — do not edit.\nexport const FILES: Record<string, { type: string; b64: string }> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Embedded ${files.length} files.`);
